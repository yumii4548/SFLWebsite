#!/usr/bin/env python3
"""Generate responsive WebP variants and images/responsive.js.

Run from anywhere: python scripts/optimize-images.py
Originals are never modified.
"""

import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
IMG_DIR = ROOT / "images"
WIDTHS = (480, 960, 1280)
QUALITY = 76
METHOD = 6
RESAMPLE = getattr(Image, "Resampling", Image).LANCZOS


def variants_for(width):
    return [w for w in WIDTHS if w < width]


def main():
    files = sorted(
        p for p in IMG_DIR.glob("*.webp")
        if not re.search(r"-(480|960|1280|1440)\.webp$", p.name)
    )
    meta = {}
    made = 0
    skipped = 0

    for src in files:
        with Image.open(src) as im:
            width, height = im.size
            mode = "RGBA" if im.mode in ("RGBA", "LA") else "RGB"
            meta[f"images/{src.name}"] = width

            targets = variants_for(width)
            if src.name == "hero-bg.webp" and width > 1440:
                targets.append(1440)

            for target in targets:
                dst = src.with_name(f"{src.stem}-{target}{src.suffix}")
                if dst.exists() and dst.stat().st_mtime >= src.stat().st_mtime:
                    skipped += 1
                    continue
                new_height = round(height * target / width)
                out = im.convert(mode).resize((target, new_height), RESAMPLE)
                out.save(dst, "WEBP", quality=QUALITY, method=METHOD)
                made += 1

    lines = [
        "/* Generated by scripts/optimize-images.py. Do not edit by hand. */",
        "(function () {",
        "  var meta = " + json.dumps(meta, ensure_ascii=False, separators=(",", ":")) + ";",
        "  function build(src) {",
        "    var w = meta[src];",
        "    if (!w) return '';",
        "    var base = src.replace(/\\.webp$/i, '');",
        "    var out = [];",
        "    if (w > 480) out.push(base + '-480.webp 480w');",
        "    if (w > 960) out.push(base + '-960.webp 960w');",
        "    if (w > 1280) out.push(base + '-1280.webp 1280w');",
        "    out.push(src + ' ' + w + 'w');",
        "    return out.join(', ');",
        "  }",
        "  window.imgAttrs = function (src, sizes) {",
        "    var ss = build(src);",
        "    return ss ? ' srcset=\"' + ss + '\" sizes=\"' + sizes + '\"' : '';",
        "  };",
        "})();",
        "",
    ]
    (IMG_DIR / "responsive.js").write_text("\n".join(lines), encoding="utf-8")
    print("images: %d, variants written: %d, up-to-date: %d" % (len(files), made, skipped))


if __name__ == "__main__":
    main()
